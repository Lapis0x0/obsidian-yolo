// Watches first-party module sources and rebuilds their artifacts, so a
// module edit reaches the dev vault the same way a host edit does.
//
// `npm run dev` builds modules once at startup and then only watches the host
// bundle, host styles, and already-built artifacts — nothing rebuilt module
// sources. Module artifacts are content-addressed and only re-evaluated when
// the plugin activates, so without this watcher a module edit is invisible
// until someone remembers to run `npm run module:build` by hand.
//
// The full build is rerun (never `--module <id>`) because `modules/bundled.json`
// — the dev install channel's catalog — is only regenerated by a full build,
// and it must stay consistent with the artifacts it describes. That costs well
// under a second for every first-party module together.

import { spawn } from 'node:child_process'
import { utimes, watch } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
)
const modulesDir = path.join(repositoryRoot, 'modules')
const buildScript = path.join(
  repositoryRoot,
  'scripts',
  'build-first-party-modules.mjs',
)
const hostBundle = path.join(repositoryRoot, 'main.js')
const DEBOUNCE_MS = 150

let pendingTimer = null
let running = false
let rebuildRequested = false

/**
 * Only hand-edited sources trigger a rebuild. An allowlist rather than an
 * ignore list: the build writes its artifacts back under `modules/`, and any
 * rule loose enough to let those through would make the watcher retrigger
 * itself forever.
 */
function isModuleSource(relativePath) {
  const parts = relativePath.split('/')
  if (parts.length < 3) return false
  const [, fileOrDir] = parts.slice(1)
  return (
    fileOrDir === 'src' ||
    ((fileOrDir === 'module.config.json' || fileOrDir === 'package.json') &&
      parts.length === 3)
  )
}

function runBuild() {
  running = true
  const child = spawn(process.execPath, [buildScript], {
    cwd: repositoryRoot,
    stdio: 'inherit',
  })
  child.on('close', (code) => {
    running = false
    if (code === 0) {
      // Obsidian's hot-reload plugin only watches `main.js` / `styles.css` at
      // the plugin root, and a module is only re-evaluated when the plugin
      // activates. Bumping the host bundle's mtime is what turns a rebuilt
      // module into a reloaded module; without hot-reload installed it is an
      // inert timestamp change.
      const now = new Date()
      void utimes(hostBundle, now, now).catch(() => {})
      console.log('[dev-modules] rebuilt')
    } else {
      console.error(`[dev-modules] build failed with exit code ${code}`)
    }
    if (rebuildRequested) {
      rebuildRequested = false
      runBuild()
    }
  })
  child.on('error', (error) => {
    running = false
    console.error('[dev-modules] build could not start:', error)
  })
}

function scheduleBuild() {
  if (pendingTimer) clearTimeout(pendingTimer)
  pendingTimer = setTimeout(() => {
    pendingTimer = null
    if (running) rebuildRequested = true
    else runBuild()
  }, DEBOUNCE_MS)
}

console.log('[dev-modules] watching modules/*/src')
const watcher = watch(modulesDir, { recursive: true })
for await (const event of watcher) {
  const filename = event.filename?.toString().replaceAll('\\', '/')
  if (!filename) continue
  if (isModuleSource(`modules/${filename}`)) scheduleBuild()
}
